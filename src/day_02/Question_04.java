package day_02;

public class Question_04 {
	public static void main(String args[]) {
		int x =10;
		System.out.println("x = " + x);
		x += 10;
		System.out.println("x += 10: " + x);
		x -= 10;
		System.out.println("x -= 10: " + x);
		x *= 2;
		System.out.println("x *= 10: " + x);
		x /= 2;
		System.out.println("x /= 10: " + x);
	}
}
