package day_01;

public class VariablesAndDataTypesDemo {
	public static void main(String[] args) {
		//declaring all the variables with proper data types
		int number = 10;
		double dNumber = 10.242;
		char character = 'a';
		boolean bo= false; //can be true and false
		String str= "Ali akbar is learning java";
		
		//printing the values
		System.out.println("(int) number = "+number);
		System.out.println("(double) dNumber = " + dNumber);
		System.out.println("(char) character = " + character);
		System.out.println("(boolean) bo = " + bo);
		System.out.println("(String) str = " + str);
	}
}
