package day_07;

public class Calculator {
	
	//methods
	//addition
	public double add(double num1, double num2) {
		return num1 + num2;
	}
	//subtraction
	public double subtract(double num1, double num2) {
		return num1 - num2;
	}
	//multiply
	public double mult(double num1, double num2) {
		return num1 * num2;
	}
	//division
	public double divide(double num1, double num2) {
		return num1 / num2;
	}
}
